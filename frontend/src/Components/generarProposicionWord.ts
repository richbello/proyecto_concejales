export async function generarProposicionWord(datos: DatosGeneracion) {
  const generador = P[datos.tipoProposicion as keyof typeof P];
  const lineas = generador(datos);

  const doc = new Document({
    sections: [{
      properties: {},
      children: [
        new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: 'XBOG CONTROL', bold: true, size: 28 })] }),
        new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 300 }, children: [new TextRun({ text: 'Sistema de Control Legislativo', size: 16 })] }),
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          rows: [
            new TableRow({ height: { value: 0, rule: HeightRule.AUTO }, children: [
              new TableCell({ width: { size: 30, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text: 'Localidad:', bold: true, size: 20 })] })] }),
              new TableCell({ width: { size: 70, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text: datos.localidad, size: 20 })] })] }),
            ]}),
            new TableRow({ height: { value: 0, rule: HeightRule.AUTO }, children: [
              new TableCell({ width: { size: 30, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text: 'Edil/Concejal:', bold: true, size: 20 })] })] }),
              new TableCell({ width: { size: 70, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text: datos.edil, size: 20 })] })] }),
            ]}),
            new TableRow({ height: { value: 0, rule: HeightRule.AUTO }, children: [
              new TableCell({ width: { size: 30, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text: 'Fecha:', bold: true, size: 20 })] })] }),
              new TableCell({ width: { size: 70, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text: datos.fecha, size: 20 })] })] }),
            ]}),
          ],
        }),
        new Paragraph({ spacing: { after: 300 }, children: [new TextRun({ text: '' })] }),
        ...lineas.map((linea) => new Paragraph({ spacing: { after: 80 }, alignment: AlignmentType.JUSTIFIED, children: [new TextRun({ text: linea, size: 20 })] })),
      ],
    }],
  });

  const blob = await Packer.toBlob(doc);
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = 'Proposicion_' + (datos.anomalia.titulo ? datos.anomalia.titulo.substring(0, 15).replace(/\s+/g, '_') : 'documento') + '.docx';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
